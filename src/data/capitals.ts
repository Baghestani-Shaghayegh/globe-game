/** The capital to show for a country, or null if the game can't ask about it. */
export function capitalOf(geoName: string): string | null {
  return CAPITALS[geoName]?.[0] ?? null;
}

/** Every spelling accepted as that country's capital. */
export function capitalsFor(geoName: string): string[] {
  return CAPITALS[geoName] ?? [];
}
