/**
 * Writes src/theme-light.css: light mode, made by flipping Tailwind's colour
 * scales end for end, and the "night" scopes that stay dark inside it.
 *
 *   node scripts/build-theme-light.mjs
 *
 * Run it again after adding a colour family to FAMILIES, or after a Tailwind
 * upgrade changes the palette. Don't edit the output by hand.
 */
import { readFileSync, writeFileSync } from "node:fs";

// Every colour family the app's classes use. A family missing from here keeps
// its dark-mode shades in light mode.
const FAMILIES = ["zinc", "gray", "sky", "teal", "rose", "amber", "emerald", "violet", "red", "blue"];
const STEPS = [50, 100, 200, 300, 400, 600, 700, 800, 900, 950];
const MIRROR = (step) => (step === 50 ? 950 : step === 950 ? 50 : 1000 - step);

const css = readFileSync("node_modules/tailwindcss/theme.css", "utf8");
const value = (name) => {
  const match = css.match(new RegExp(`--color-${name}:\\s*([^;]+);`));
  if (!match) throw new Error(`No --color-${name} in Tailwind's theme`);
  return match[1].trim();
};

const light = [];
const night = [];
for (const family of FAMILIES) {
  for (const step of STEPS) {
    light.push(`  --color-${family}-${step}: ${value(`${family}-${MIRROR(step)}`)};`);
    night.push(`  --color-${family}-${step}: ${value(`${family}-${step}`)};`);
  }
}
light.push(`  --color-white: ${value("zinc-950")};`);
night.push(`  --color-white: ${value("white")};`);

writeFileSync(
  "src/theme-light.css",
  `/*
 * Generated by scripts/build-theme-light.mjs — edit that, not this.
 *
 * Light mode, made by flipping each colour scale end for end (50 <-> 950,
 * 100 <-> 900 and so on), so every pairing the dark design made — pale text on
 * dark ground, a bright button with dark words on it — becomes its mirror
 * without a second design to keep in step. "white" turns to ink for the same
 * reason: hairlines and washes drawn in white over dark are drawn in ink over
 * light.
 */
:root[data-theme="light"] {
${light.join("\n")}
}

/*
 * Night scopes stay dark in light mode: the full-screen globe games are a
 * night scene either way, and their panels sit on that dark globe.
 */
:root[data-theme="light"] .night {
${night.join("\n")}
}
`
);
console.log("wrote src/theme-light.css");
